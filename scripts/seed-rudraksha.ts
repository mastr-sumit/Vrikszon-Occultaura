async function seed() {
  console.log("Seeding Rudraksha Category & Products...");

  // Ensure Rudraksha Category exists
  let rudrakshaCat = await prisma.category.findFirst({
    where: { name: { equals: "Rudraksha", mode: "insensitive" }, type: "PRODUCT" },
  });

  if (!rudrakshaCat) {
    rudrakshaCat = await prisma.category.create({
      data: {
        name: "Rudraksha",
        slug: "rudraksha",
        type: "PRODUCT",
      },
    });
    console.log("Created Rudraksha Category in DB:", rudrakshaCat.id);
  } else {
    console.log("Found existing Rudraksha Category:", rudrakshaCat.id);
  }

  for (const item of RUDRAKSHA_PRODUCTS) {
    const existing = await prisma.product.findUnique({
      where: { slug: item.slug },
    });

    const benefitsStr = JSON.stringify(item.benefits);

    if (existing) {
      const updated = await prisma.product.update({
        where: { id: existing.id },
        data: {
          name: item.name,
          category: item.category,
          categoryId: rudrakshaCat.id,
          subtitle: item.subtitle,
          shortDescription: item.shortDescription,
          benefits: benefitsStr,
          price: item.price,
          priceAAA: item.priceAAA,
          image: item.image,
          icon: item.icon,
          featured: item.featured,
          enabled: item.enabled,
          href: item.href,
          variantsNote: item.variantsNote,
        },
      });
      console.log(`Updated ${updated.name} (AA: ₹${updated.price}, AAA: ₹${updated.priceAAA})`);
    } else {
      const created = await prisma.product.create({
        data: {
          slug: item.slug,
          name: item.name,
          category: item.category,
          categoryId: rudrakshaCat.id,
          subtitle: item.subtitle,
          shortDescription: item.shortDescription,
          benefits: benefitsStr,
          price: item.price,
          priceAAA: item.priceAAA,
          image: item.image,
          icon: item.icon,
          featured: item.featured,
          enabled: item.enabled,
          href: item.href,
          variantsNote: item.variantsNote,
        },
      });
      console.log(`Created ${created.name} (AA: ₹${created.price}, AAA: ₹${created.priceAAA})`);
    }
  }

  console.log("All Rudraksha products seeded successfully!");
}

seed()
  .catch((e) => {
    console.error("Seed error:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
